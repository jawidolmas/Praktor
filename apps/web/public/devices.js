// Devices tab: show a one-time pairing QR for the iOS app, and list / revoke
// paired devices. Everything here talks to local-only routes (/api/pairing,
// /api/devices) that the server refuses to anyone but this machine.

const pairingEl = document.getElementById("pairing");
const devicesEl = document.getElementById("devices");

let pairing = null; // { expiresAt, knownIds: Set<string>, timer }
let pendingRevoke = null; // device id awaiting inline confirmation
let lastDevices = [];

function formatCountdown(ms) {
  const s = Math.max(0, Math.ceil(ms / 1000));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

// Server messages mark commands with `backticks`; show those as code. The
// text is escaped first, so only this one transformation adds markup.
function withInlineCode(text) {
  return escapeHtml(text).replace(/`([^`]+)`/g, "<code>$1</code>");
}

function renderPairIdle(message, tone) {
  pairing = null;
  pairingEl.innerHTML = `
    ${message ? `<div class="pair-note ${tone || ""}">${withInlineCode(message)}</div>` : ""}
    <button class="btn-primary" id="pairStart">Show pairing code</button>`;
}

function renderPairCode(data) {
  // qrSvg is generated by this server's own QR encoder from a link it built
  // itself, never from request input, so it's safe to insert as markup.
  pairingEl.innerHTML = `
    <div class="pair-card">
      <div class="qr-frame" aria-label="Pairing QR code">${data.qrSvg}</div>
      <div class="pair-side">
        <div class="pair-step"><span class="pair-num">1</span>Open the Camera app on your iPhone.</div>
        <div class="pair-step"><span class="pair-num">2</span>Point it at the code and tap the Praktor link.</div>
        <div class="pair-step"><span class="pair-num">3</span>Confirm the pairing in the app.</div>
        <div class="pair-meta">
          <span class="muted">Connects to</span> <span class="mono">${escapeHtml(data.url)}</span>
        </div>
        <div class="pair-meta">
          <span class="muted">Expires in</span> <span class="mono" id="pairCountdown">${formatCountdown(data.expiresAt - Date.now())}</span>
        </div>
        <div class="pair-actions">
          <button class="btn-ghost" id="pairCancel">Cancel</button>
        </div>
      </div>
    </div>`;
}

async function startPairing() {
  const { ok, data } = await postJSON("/api/pairing", {});
  if (!ok) {
    renderPairIdle(data.error || "Couldn't create a pairing code.", "warn");
    return;
  }
  if (pairing) clearInterval(pairing.timer);
  pairing = {
    expiresAt: data.expiresAt,
    knownIds: new Set(lastDevices.map((d) => d.id)),
    timer: setInterval(tickPairing, 1000),
  };
  renderPairCode(data);
}

function tickPairing() {
  if (!pairing) return;
  const left = pairing.expiresAt - Date.now();
  const el = document.getElementById("pairCountdown");
  if (el) el.textContent = formatCountdown(left);
  if (left <= 0) {
    clearInterval(pairing.timer);
    renderPairIdle("That code expired. Show a new one when your phone is ready.");
  }
}

async function cancelPairing() {
  if (pairing) clearInterval(pairing.timer);
  await postJSON("/api/pairing/cancel", {});
  renderPairIdle();
}

function renderDevices(list) {
  if (list.length === 0) {
    devicesEl.innerHTML = `<div class="empty">No devices yet. Pair your iPhone above to follow Praktor from anywhere.</div>`;
    return;
  }
  devicesEl.innerHTML = `<div class="device-list">${list.map(renderDevice).join("")}</div>`;
}

function renderDevice(d) {
  const revoked = d.revokedAt !== null;
  const status = revoked
    ? `<span class="badge status-failed">revoked ${timeAgo(d.revokedAt)}</span>`
    : `<span class="badge status-done">active</span>`;
  const seen = d.lastSeenAt ? `last seen ${timeAgo(d.lastSeenAt)}` : "never connected";
  let action = "";
  if (!revoked) {
    action =
      pendingRevoke === d.id
        ? `<span class="device-confirm">Cut off this device?</span>
           <button class="btn-danger" data-revoke-confirm="${escapeHtml(d.id)}">Revoke</button>
           <button class="btn-ghost" data-revoke-cancel>Keep</button>`
        : `<button class="btn-ghost" data-revoke="${escapeHtml(d.id)}">Revoke</button>`;
  }
  return `
    <div class="device-row${revoked ? " revoked" : ""}">
      <div class="device-main">
        <div class="device-name">${escapeHtml(d.name)}</div>
        <div class="device-meta">paired ${timeAgo(d.createdAt)} · ${seen}</div>
      </div>
      <div class="device-actions">${status}${action}</div>
    </div>`;
}

async function refreshDevices() {
  try {
    lastDevices = await fetchJSON("/api/devices");
  } catch (err) {
    console.error(err);
    return;
  }
  // A device we hadn't seen while the QR was up means the phone just
  // redeemed it — the server already invalidated the code, so say so.
  if (pairing) {
    const fresh = lastDevices.find((d) => !pairing.knownIds.has(d.id));
    if (fresh) {
      clearInterval(pairing.timer);
      renderPairIdle(`Paired with “${fresh.name}”.`, "ok");
    }
  }
  renderDevices(lastDevices);
}

document.addEventListener("click", async (e) => {
  const t = e.target;
  if (!(t instanceof Element)) return;
  if (t.closest("#pairStart")) return startPairing();
  if (t.closest("#pairCancel")) return cancelPairing();

  const ask = t.closest("[data-revoke]");
  if (ask) {
    pendingRevoke = ask.getAttribute("data-revoke");
    return renderDevices(lastDevices);
  }
  if (t.closest("[data-revoke-cancel]")) {
    pendingRevoke = null;
    return renderDevices(lastDevices);
  }
  const confirmBtn = t.closest("[data-revoke-confirm]");
  if (confirmBtn) {
    const id = confirmBtn.getAttribute("data-revoke-confirm");
    pendingRevoke = null;
    const { ok, data } = await postJSON(`/api/devices/${encodeURIComponent(id)}/revoke`, {});
    if (!ok) console.error(data.error);
    return refreshDevices();
  }
});

// Poll only while the tab is actually on screen (or a code is showing), so
// an idle dashboard doesn't keep hitting this.
setInterval(() => {
  const page = document.querySelector('.tab-page[data-tab="devices"]');
  if (pairing || (page && !page.hidden)) refreshDevices();
}, 2000);
refreshDevices();
